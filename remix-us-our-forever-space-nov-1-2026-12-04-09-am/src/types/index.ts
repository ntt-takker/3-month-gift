export type PartnerId = 'partner1' | 'partner2';

export interface PartnerProfile {
  id: PartnerId;
  name: string;        // Real name (e.g. Manil / Sarah)
  nickname: string;    // Set ONLY by the other partner!
  nicknameSetBy: string;
  birthday: string;    // YYYY-MM-DD
  avatar: string;      // Emoji or image url
}

export interface CoupleProfile {
  partner1: PartnerProfile;
  partner2: PartnerProfile;
  anniversaryDate: string; // YYYY-MM-DD (e.g. 2026-07-31)
  passcode: string;        // 4 digits shared fallback (e.g. "0731")
  passcodeHint: string;
  partner1Passcode?: string; // Manil's private passcode (default: "1214")
  partner1PasscodeHint?: string;
  partner2Passcode?: string; // Her private passcode (default: "0418")
  partner2PasscodeHint?: string;
  currentViewer: PartnerId; // 'partner1' (Him) or 'partner2' (Her)
  ambientSoundEnabled: boolean;
  darkMode?: boolean;
}

export interface Compliment {
  id: string;
  from: PartnerId;
  to: PartnerId;
  content: string;
  timestamp: number;
  relationshipDay: number;
  isFavorite: boolean;
}

export interface Milestone {
  id: string;
  title: string;
  date: string;
  type: 'anniversary' | 'birthday' | 'custom' | 'day_count';
  description: string;
  note?: string;
  photoUrl?: string;
  badge?: string;
  isAutoGenerated?: boolean;
}

export interface PhotoMemory {
  id: string;
  url: string;
  caption: string;
  date: string;
  location?: string;
  addedBy: PartnerId;
  addedAt: number;
  isFavorite: boolean;
}

export interface ToDoItem {
  id: string;
  title: string;
  category: 'date' | 'travel' | 'cute' | 'movie' | 'food';
  addedBy: PartnerId;
  addedAt: number;
  completed: boolean;
  completedAt?: number;
  completedNote?: string;
  targetDate?: string; // YYYY-MM-DD for scheduled calendar overlay
}

export interface DailyMood {
  emoji: string;
  statusText: string;
  updatedAt: number;
  lastPoke?: {
    type: 'hug' | 'kiss' | 'love';
    from: PartnerId;
    timestamp: number;
  };
}

export interface LoveDrop {
  id: string;
  from: PartnerId;
  to: PartnerId;
  type: 'note' | 'photo';
  content: string;
  photoUrl?: string;
  isSurprise: boolean;
  isRevealed: boolean;
  timestamp: number;
  heartCount: number;
}

export interface MediaRecommendation {
  id: string;
  title: string;
  creator?: string; // artist, director, author
  category: 'song' | 'movie' | 'book' | 'spot';
  note: string;
  url?: string;
  suggestedBy: PartnerId;
  suggestedAt: number;
  status: 'to_experience' | 'in_progress' | 'completed';
  rating?: number; // 1-5
  sharedReview?: string;
}

export interface SharedSpotifyPlaylist {
  url: string;
  embedUrl: string;
  title: string;
  description: string;
  updatedBy: PartnerId;
  updatedAt: number;
}

export interface ChatMessage {
  id: string;
  from: PartnerId;
  text: string;
  timestamp: number;
  reaction?: string;
  isSticker?: boolean;
}

export type GameMode = 'apart' | 'public' | 'dark';

export interface TruthOrDareCard {
  id: string;
  type: 'truth' | 'dare';
  mode: GameMode;
  prompt: string;
  isCustom?: boolean;
  addedBy?: PartnerId;
}

