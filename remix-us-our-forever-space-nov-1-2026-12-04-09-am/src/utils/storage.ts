// Helper to convert Spotify share links into playable embed URLs
export function formatSpotifyEmbedUrl(input: string): string {
  if (!input) return 'https://open.spotify.com/embed/playlist/37i9dQZF1DXcBWIGoYBM5M?utm_source=generator';
  const trimmed = input.trim();
  if (trimmed.includes('open.spotify.com/embed/')) {
    return trimmed.includes('utm_source=generator') ? trimmed : `${trimmed}${trimmed.includes('?') ? '&' : '?'}utm_source=generator`;
  }
  const match = trimmed.match(/open\.spotify\.com\/(playlist|album|track|artist)\/([a-zA-Z0-9]+)/);
  if (match) {
    const type = match[1];
    const id = match[2];
    return `https://open.spotify.com/embed/${type}/${id}?utm_source=generator`;
  }
  const uriMatch = trimmed.match(/spotify:(playlist|album|track):([a-zA-Z0-9]+)/);
  if (uriMatch) {
    return `https://open.spotify.com/embed/${uriMatch[1]}/${uriMatch[2]}?utm_source=generator`;
  }
  return trimmed;
}

