// Helper to calculate relationship days accurately
export function getRelationshipDays(anniversaryDateStr: string): number {
  const start = new Date(anniversaryDateStr).getTime();
  const now = Date.now();
  const diffTime = Math.max(0, now - start);
  return Math.floor(diffTime / (1000 * 60 * 60 * 24));
}

// Helper to determine if today marks a special anniversary milestone or special milestone day
export function checkIsMilestoneToday(
  anniversaryDateStr: string,
  currentTimestamp: number = Date.now(),
  milestones: Milestone[] = []
): { isMilestone: boolean; title: string; subtitle: string; badge: string } | null {
  const currentDate = new Date(currentTimestamp);
  const curYear = currentDate.getFullYear();
  const curMonth = currentDate.getMonth() + 1;
  const curDay = currentDate.getDate();
  const todayDateStr = `${curYear}-${String(curMonth).padStart(2, '0')}-${String(curDay).padStart(2, '0')}`;

  // Check if today matches any explicitly set milestone
  const matchingMilestone = milestones.find((m) => m.date === todayDateStr);
  if (matchingMilestone) {
    return {
      isMilestone: true,
      title: matchingMilestone.title,
      subtitle: matchingMilestone.description || 'A cherished moment in our love story',
      badge: matchingMilestone.badge || 'Today ✨',
    };
  }

  // Calculate elapsed days
  const startDate = new Date(anniversaryDateStr).getTime();
  const diffDays = Math.floor(Math.max(0, currentTimestamp - startDate) / (1000 * 60 * 60 * 24));

  // Check special milestone round day counts
  if (diffDays === 1) {
    return {
      isMilestone: true,
      title: 'Our Very First Day Together! 🌹',
      subtitle: 'Where our forever journey started.',
      badge: 'Day 1',
    };
  }
  if (diffDays === 50 || diffDays === 100 || diffDays === 200 || diffDays === 300 || diffDays === 500 || diffDays === 1000) {
    return {
      isMilestone: true,
      title: `Celebration: ${diffDays} Days Together! ✨`,
      subtitle: `${diffDays} days of laughing, holding hands, and loving each other.`,
      badge: `${diffDays} Days`,
    };
  }

  // Check monthly anniversary (same day of month)
  const annivDate = new Date(anniversaryDateStr);
  const annivDay = annivDate.getDate();
  if (curDay === annivDay && diffDays >= 28) {
    // Calculate months elapsed
    const elapsedMonths = (curYear - annivDate.getFullYear()) * 12 + (curMonth - 1 - annivDate.getMonth());
    if (elapsedMonths > 0) {
      const isYearly = elapsedMonths % 12 === 0;
      const title = isYearly
        ? `Happy ${elapsedMonths / 12} Year Anniversary! 💍`
        : `Happy ${elapsedMonths}${elapsedMonths === 1 ? 'st' : elapsedMonths === 2 ? 'nd' : elapsedMonths === 3 ? 'rd' : 'th'} Month Anniversary! 🥂`;
      return {
        isMilestone: true,
        title,
        subtitle: `${diffDays} days of choosing each other every single day.`,
        badge: isYearly ? '1 Year Anniversary ✨' : `${elapsedMonths} Months ✨`,
      };
    }
  }

  return null;
}

// Storage managers with fallback to initial data
export function loadFromStorage<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return fallback;
    return JSON.parse(raw);
  } catch {
    return fallback;
  }
}

export function saveToStorage<T>(key: string, value: T): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch (err) {
    console.error('Storage save error:', err);
  }
}

